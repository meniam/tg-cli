def is_cyrillic(word: str) -> bool:
    """В слове есть кириллица."""
    return _CYRILLIC.search(word) is not None


def stem(word: str) -> str:
    """Лёгкая основа русского слова: без возвратной частицы и окончания.

    Основа не короче четырёх букв: короткие слова («вход», «цена») не режутся, иначе
    префикс совпадёт со слишком многим.

    >>> stem("проксирует"), stem("администратора"), stem("отключение"), stem("вход")
    ('прокс', 'администратор', 'отключ', 'вход')

    Returns:
        Основа русского слова.

    """
    if not is_cyrillic(word) or len(word) <= _MIN_STEM:
        return word
    base = word
    for particle in ("ся", "сь"):
        if base.endswith(particle) and len(base) - 2 >= _MIN_STEM:
            base = base[:-2]
            break
    borrowed = _BORROWED_VERB.search(base)
    if borrowed is not None and borrowed.start() >= 3:
        return base[: borrowed.start()]
    for ending in _ENDINGS:
        if base.endswith(ending) and len(base) - len(ending) >= _MIN_STEM:
            return base[: -len(ending)]
    return base


def english(word: str, stem_value: str) -> tuple[str, ...]:
    """Английские слова из кода для русского слова; пусто, если термина нет.

    Сначала сверяется само слово, затем основа: основа «формируется» — «форм», и по ней
    одной не отличить формирование от формы.

    Returns:
        Английские варианты термина для расширения запроса.

    """
    for candidate in (word, stem_value):
        for key, words in _GLOSSARY_PAIRS:
            if candidate.startswith(key):
                return words
    return ()


def translit(word: str) -> str:
    """Латиница для имени собственного: «браин» → «brain»."""
    return word.translate(_TRANSLIT)
