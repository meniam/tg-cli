"""Признак сгенерированного файла: заглушка генератора не должна обгонять ручной код.

Одноимённый символ из сгенерированного клиента или протокола часто выходит в выдаче
первым, хотя тела у него нет и отвечать на вопрос агента он не может. Признак не
фильтрует выдачу, а только опускает такие записи ниже ручных при равном совпадении.

Два признака. Путь: соглашения генераторов вида ``_pb2.py`` и ``.generated.ts``.
Баннер в начале файла: ``@generated``, «do not edit», «file generated by». Заготовка,
которую предлагают править («Auto-generated Migration: Please modify to your needs!»
у миграций Doctrine), сгенерированной не считается: её код пишут руками.
"""

import re

HEADER_LINES = 12
HEADER_BYTES = 2048

_PATH = re.compile(
    r"(?:^|/)__generated__/"
    r"|_pb2(?:_grpc)?\.pyi?$"
    r"|(?:\.pb|_pb|_grpc_pb)\.[cm]?[jt]sx?$"
    r"|\.pb(?:\.gw)?\.go$"
    r"|\.(?:generated|gen)\.[a-z]+$"
)
_BANNER = re.compile(
    r"@generated\b"
    r"|\bdo not (?:edit|modify|make (?:direct )?changes)\b"
    r"|\bdon'?t (?:edit|modify)\b"
    r"|\bshould not be (?:edited|modified)\b"
    r"|\b(?:file|code|class) (?:was |is )?(?:auto-?|automatically )?generated by\b",
    re.IGNORECASE,
)


def is_generated(path: str, source: bytes) -> bool:
    r"""Файл создан генератором: по соглашению об имени или по баннеру в начале.

    >>> is_generated("src/api/client.generated.ts", b"")
    True
    >>> is_generated("next-env.d.ts", b"// NOTE: This file should not be edited\\n")
    True
    >>> is_generated(
    ...     "Version1.php",
    ...     b"/** Auto-generated Migration: Please modify to your needs! */",
    ... )
    False

    Returns:
        ``True``, если файл сгенерирован.
    """
    if _PATH.search(path):
        return True
    head = source[:HEADER_BYTES].decode("utf-8", errors="replace")
    return bool(_BANNER.search("\n".join(head.splitlines()[:HEADER_LINES])))
